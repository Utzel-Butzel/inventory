import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const catalog = JSON.parse(await readFile(new URL("localization/native.json", root), "utf8"));
const check = process.argv.includes("--check");
const xml = (value) => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

for (const language of ["en", "de"]) {
  const entries = Object.entries(catalog);
  for (const [key, value] of entries) {
    if (!value[language]?.trim()) throw new Error(`Missing ${language} translation: ${key}`);
    const tokens = (text) => [...text.matchAll(/\{(\d+)\}/g)].map((match) => match[1]).sort();
    if (JSON.stringify(tokens(value.en)) !== JSON.stringify(tokens(value.de))) {
      throw new Error(`Interpolation mismatch: ${key}`);
    }
  }
  const outputs = [
    [`ios/Inventory/Inventory/${language}.lproj/Localizable.strings`,
      "/* Generated by scripts/sync-native-locales.mjs. Edit localization/native.json. */\n" +
      entries.map(([key, value]) => `${JSON.stringify(key)} = ${JSON.stringify(value[language])};`).join("\n") + "\n"],
    [`android/app/src/main/res/values${language === "en" ? "" : "-de"}/strings.xml`,
      '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/sync-native-locales.mjs. Edit localization/native.json. -->\n<resources>\n' +
      entries.map(([key, value]) => `    <string name="${key}" formatted="false">${xml(JSON.stringify(value[language]).replaceAll("'", "\\'"))}</string>`).join("\n") + "\n</resources>\n"],
  ];
  // Explicit English participates in Android's ordered locale matching; values/
  // still supplies the English fallback when no supported language is requested.
  if (language === "en") {
    outputs.push(["android/app/src/main/res/values-en/strings.xml", outputs[1][1]]);
  }
  for (const [path, contents] of outputs) {
    const url = new URL(path, root);
    if (check) {
      if (await readFile(url, "utf8") !== contents) throw new Error(`Outdated translations: ${path}`);
    } else {
      await mkdir(fileURLToPath(new URL(".", url)), { recursive: true });
      await writeFile(url, contents);
    }
  }
}
